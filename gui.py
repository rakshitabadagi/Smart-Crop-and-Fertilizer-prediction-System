import tkinter as tk
import joblib
model=joblib.load("crop_model.pkl")
le=joblib.load("label_encoder.pkl")
def predict_crop():
    N=float(nitrogen.get())
    P=float(phosphorus.get())
    K=float(potassium.get())
    temp=float(temperature.get())
    hum=float(humidity.get())
    ph_value=float(ph.get())
    rain=float(rainfall.get())
    prediction=model.predict([[N,P,K,temp,hum,ph_value,rain]])
    crop=le.inverse_transform(prediction)
    result.config(text="Recommended Crop:"+ crop[0])
root=tk.Tk()
root.title("Smart Crop Recommendation System")
root.geometry("500x500")
tk.Label(root,text="Smart Crop Recommendation System", font=("Arial",16)).pack(pady=10)
tk.Label(root,text="Nitrogen").pack()
nitrogen=tk.Entry(root)
nitrogen.pack()
tk.Label(root,text="Phosphorus").pack()
phosphorus=tk.Entry(root)
phosphorus.pack()
tk.Label(root,text="Potassium").pack()
potassium=tk.Entry(root)
potassium.pack()
tk.Label(root,text="Temperature").pack()
temperature=tk.Entry(root)
temperature.pack()
tk.Label(root,text="Humdity").pack()
humidity=tk.Entry(root)
humidity.pack()
tk.Label(root,text="pH").pack()
ph=tk.Entry(root)
ph.pack()
tk.Label(root,text="Rainfall").pack()
rainfall=tk.Entry(root)
rainfall.pack()
tk.Button(root,text="Predict Crop", command=predict_crop).pack(pady=20)
result=tk.Label(root,text="",font=("Arial",12))
result.pack()
root.mainloop()


